#!/usr/bin/env python3
"""Generates libs/pdf/src/fontdata.inc: the PDF standard-14 advance widths
(Adobe AFM metrics, via reportlab) for the WinAnsi code page, and small
anti-aliased glyph bitmaps of GNU FreeFont (GPL-3.0+ with font exception,
see third_party/freefont) used to rasterise previews. Needs Pillow,
reportlab and the FreeFont TTFs.

    python3 libs/pdf/tools/gen_fontdata.py /usr/share/fonts/truetype/freefont > libs/pdf/src/fontdata.inc
"""
import sys
import zlib

from PIL import Image, ImageDraw, ImageFont
from reportlab.pdfbase.pdfmetrics import stringWidth

EM = 32
STD = ["Helvetica", "Helvetica-Bold", "Helvetica-Oblique", "Helvetica-BoldOblique",
       "Times-Roman", "Times-Bold", "Times-Italic", "Times-BoldItalic",
       "Courier", "Courier-Bold", "Courier-Oblique", "Courier-BoldOblique"]
RASTER = ["FreeSans", "FreeSansBold", "FreeSerif", "FreeSerifBold", "FreeMono", "FreeMonoBold"]


def char(b):
    try:
        return bytes([b]).decode("cp1252")
    except UnicodeDecodeError:
        return None


def main():
    folder = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/freefont"
    out = ["// Generated by libs/pdf/tools/gen_fontdata.py; do not edit.",
           "// Widths: Adobe standard-14 AFM metrics. Glyphs: GNU FreeFont, GPL-3.0+ with font exception.",
           "static const unsigned short kWidths[12][224] = {"]
    for name in STD:
        row = []
        for b in range(32, 256):
            c = char(b)
            row.append(str(int(round(stringWidth(c, name, 1000)))) if c else "0")
        out.append("    {" + ",".join(row) + "},")
    out.append("};")
    out.append("static const int kGlyphEm = %d;" % EM)
    out.append("// per glyph: left, top (above baseline), width, height, offset into the inflated blob")
    out.append("static const int kGlyphs[6][224][5] = {")
    blob = bytearray()
    for name in RASTER:
        font = ImageFont.truetype("%s/%s.ttf" % (folder, name), EM)
        rows = []
        for b in range(32, 256):
            c = char(b)
            if not c or c.isspace() or c == "\xa0":
                rows.append("{0,0,0,0,0}")
                continue
            l, t, r, btm = font.getbbox(c, anchor="ls")
            w, h = r - l, btm - t
            if w <= 0 or h <= 0:
                rows.append("{0,0,0,0,0}")
                continue
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-l, -t), c, font=font, fill=255, anchor="ls")
            rows.append("{%d,%d,%d,%d,%d}" % (l, -t, w, h, len(blob)))
            blob += bytes((v + 8) // 17 for v in img.tobytes())  # 16 levels compress far better
        out.append("    {" + ",".join(rows) + "},")
    out.append("};")
    packed = zlib.compress(bytes(blob), 9)
    out.append("static const unsigned kGlyphBlobSize = %d;" % len(blob))
    out.append("static const unsigned char kGlyphBlob[%d] = {" % len(packed))
    for i in range(0, len(packed), 40):
        out.append(",".join(str(x) for x in packed[i:i + 40]) + ",")
    out.append("};")
    print("\n".join(out))


main()
